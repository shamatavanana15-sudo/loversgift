            const action = event.target.closest('[data-action]')?.dataset.action;
            if (!action) return;
            const latestItems = readCart();
            const target = latestItems.find(entry => entry.id === item.id && entry.variantId === item.variantId);
            if (!target) return;
            const stock = target.product.variants?.find(variant => variant.id === target.variantId)?.stock ?? target.product.stock;
            const cap = Number.isFinite(stock) ? stock : 99;
            if (action === 'increase') target.quantity = Math.min(cap, target.quantity + 1);
