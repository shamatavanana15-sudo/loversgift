function applyProductImage(card) {
    const image = card.querySelector('.product-photo img');
    const name = card.querySelector('.product-title')?.textContent.trim();
    if (!image || !name) return;
    const brand = card.querySelector('.product-brand')?.textContent.trim() || '';
    const price = card.querySelector('.product-price')?.textContent.match(/[\d.]+/)?.[0] || '';
    const photo = getProductPhoto(name, brand, price);
    if (photo) {
        image.src = photo[0];
        image.alt = photo[1];
        image.dataset.productPlaceholder = '';
        image.dataset.productPhoto = 'pexels';
        return;
    }
    if (!placeholderProductNames.has(name)) return;
    image.src = createProductPlaceholder(name, `${name}|${brand}|${price}`);
    image.alt = `${name} — ${productImageKind(name)} placeholder`;
    image.dataset.productPlaceholder = 'true';
}

function productFromCard(card) {
    const title = card.querySelector('.product-title');
    const brand = card.querySelector('.product-brand');
    const priceNode = card.querySelector('.product-price');
    const image = card.querySelector('.product-photo img');
    if (!title || !brand || !priceNode || !image) return null;

    const price = Number(priceNode.textContent.match(/[\d.]+/)?.[0]);
    if (!Number.isFinite(price)) return null;

    const source = `${title.textContent.trim()}|${brand.textContent.trim()}|${image.src}|${price}`;
    const id = `${productSlug(title.textContent)}-${productHash(source)}`;
    const isMenCardHolder = location.pathname.endsWith('/men.html') && title.textContent.includes('ბარათების ჩასადები');
    const categoryByPage = {
        '/women.html': 'ქალებისთვის',
        '/men.html': 'კაცებისთვის',
        '/perfumes.html': 'სუნამოები',
        '/accessories.html': 'აქსესუარები',
        '/gift-sets.html': 'სასაჩუქრე ნაკრები'
    };
    const product = {
        id,
        name: title.textContent.trim(),
        brand: brand.textContent.trim(),
        category: Object.entries(categoryByPage).find(([path]) => location.pathname.toLowerCase().endsWith(path))?.[1] || '',
        image: image.src,
        images: [image.src],
        imageAlt: image.alt,
        price,
        stock: null,
        description: `პროდუქტის დასახელება: ${title.textContent.trim()}. ${brand.textContent.trim()}. დამატებითი მახასიათებლები და მარაგი დასადასტურებელია.`,
        variants: isMenCardHolder ? cardHolderColors.map(color => ({ ...color, price, stock: null })) : []
    };
    return product;
}

function productUrl(product) {
    return `product.html?id=${encodeURIComponent(product.id)}&data=${encodeURIComponent(JSON.stringify(product))}`;
}

function initProductCards() {
    document.querySelectorAll('.product-card').forEach(card => {
        applyProductImage(card);
        const product = productFromCard(card);
        if (!product) return;
        card.dataset.productId = product.id;
        card.querySelectorAll('a.product-title, .product-actions a.button-outline').forEach(link => {
            link.href = productUrl(product);
        });
        card.addEventListener('click', event => {
            if (event.target.closest('a, button')) return;
            location.href = productUrl(product);
        });
        card.tabIndex = 0;
        card.addEventListener('keydown', event => {
            if (event.key !== 'Enter' || event.target.closest('a, button')) return;
            location.href = productUrl(product);
        });
    });
}

function loadProductFromLocation() {
    const params = new URLSearchParams(location.search);
    const id = params.get('id');
    const data = params.get('data');
    if (!id || !data) return null;
    try {
        const product = JSON.parse(data);
        if (!product || product.id !== id || !product.name || !product.brand || !Number.isFinite(product.price) || typeof product.image !== 'string') return null;
        if (product.name === 'Burberry Goddess Eau de Parfum with Vanilla & Lavender') {
            product.name = 'Burberry Goddess-ის პარფიუმერული წყალი ვანილისა და ლავანდის ნოტებით';
            product.description = product.description.replace('Burberry Goddess Eau de Parfum with Vanilla & Lavender', product.name);
            product.imageAlt = product.name;
        }
        const photo = getProductPhoto(product.name, product.brand, product.price);
        if (photo) {
            product.image = photo[0];
            product.images = [photo[0]];
            product.imageAlt = photo[1];
        } else if (placeholderProductNames.has(product.name)) {
            product.image = createProductPlaceholder(product.name, `${product.name}|${product.brand}|${product.price}`);
            product.images = [product.image];
            product.imageAlt = `${product.name} — ${productImageKind(product.name)} placeholder`;
        }
        return product.image.startsWith('https://') || product.image.startsWith('data:image/svg+xml;charset=utf-8,') ? product : null;
    } catch {
        return null;
    }
}

