const originals = new WeakMap();

function addPreferenceControls() {
    const tools = document.querySelector('.header-tools');
    if (!tools || tools.querySelector('.preference-tools')) return;

    const controls = document.createElement('div');
    controls.className = 'preference-tools';
    controls.innerHTML = '<div class="language-switch" role="group" aria-label="Language"><button type="button" data-language="ka" aria-label="ქართული">KA</button><button type="button" data-language="en" aria-label="English">EN</button></div><button class="theme-toggle" type="button" aria-label="მუქი რეჟიმი" title="მუქი რეჟიმი"><svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20.4 15.4A8.5 8.5 0 0 1 8.6 3.6a8.5 8.5 0 1 0 11.8 11.8Z"></path></svg></button>';
    tools.prepend(controls);

    controls.querySelectorAll('[data-language]').forEach(button => {
        button.addEventListener('click', () => setLanguage(button.dataset.language));
    });
    controls.querySelector('.theme-toggle').addEventListener('click', toggleTheme);
}

function setLanguage(language) {
    const english = language === 'en';
    document.documentElement.lang = english ? 'en' : 'ka';
    document.documentElement.dataset.language = language;

    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode(node) {
            return node.parentElement.closest('script, style, .preference-tools') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT;
        }
    });
    let node;
    while ((node = walker.nextNode())) {
        if (!originals.has(node)) originals.set(node, node.nodeValue);
        const original = originals.get(node);
        const trimmed = original.trim().replace(/\s+/g, ' ');
        const translated = english ? translations[trimmed] : null;
        if (english && translated) {
            const start = original.match(/^\s*/)[0];
            const end = original.match(/\s*$/)[0];
            node.nodeValue = `${start}${translated}${end}`;
        } else if (!english) {
            node.nodeValue = original;
        }
    }

    document.querySelectorAll('[placeholder], [aria-label], [title], img[alt]').forEach(element => {
        for (const attribute of ['placeholder', 'aria-label', 'title', 'alt']) {
            if (!element.hasAttribute(attribute)) continue;
            const key = `${attribute}:${element.getAttribute(attribute)}`;
            if (!originals.has(element)) originals.set(element, {});
            const saved = originals.get(element);
            if (!(attribute in saved)) saved[attribute] = element.getAttribute(attribute);
            const value = saved[attribute];
            const translation = attributeTranslations[value] || translations[value];
            if (english && translation) element.setAttribute(attribute, translation);
            if (!english) element.setAttribute(attribute, value);
        }
    });

    const titleKey = document.title;
    if (!originals.has(document)) originals.set(document, { title: titleKey });
    const titleData = originals.get(document);
    if (english) document.title = translations[titleData.title] || titleData.title;
    else document.title = titleData.title;

    document.querySelectorAll('[data-language]').forEach(button => {
        button.setAttribute('aria-pressed', String(button.dataset.language === language));
    });
    updateThemeControlLabel();
    localStorage.setItem(languageKey, language);
    document.dispatchEvent(new Event('loversgift:languagechange'));
    renderProductDetails();
    renderCartPage();
}

function setTheme(theme) {
    document.documentElement.dataset.theme = theme;
    const button = document.querySelector('.theme-toggle');
    if (!button) return;
    const english = document.documentElement.lang === 'en';
    const dark = theme === 'dark';
    button.setAttribute('aria-label', dark ? (english ? 'Switch to light mode' : 'ნათელ რეჟიმზე გადასვლა') : (english ? 'Switch to dark mode' : 'მუქ რეჟიმზე გადასვლა'));
    button.title = button.getAttribute('aria-label');
    button.innerHTML = dark
        ? '<svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="4"></circle><path d="M12 2v2m0 16v2M4.93 4.93l1.42 1.42m11.3 11.3 1.42 1.42M2 12h2m16 0h2M4.93 19.07l1.42-1.42m11.3-11.3 1.42-1.42"></path></svg>'
        : '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M20.4 15.4A8.5 8.5 0 0 1 8.6 3.6a8.5 8.5 0 1 0 11.8 11.8Z"></path></svg>';
    button.setAttribute('aria-pressed', String(dark));
    localStorage.setItem(themeKey, theme);
}

function updateThemeControlLabel() {
    setTheme(document.documentElement.dataset.theme || 'light');
}

function toggleTheme() {
    const next = document.documentElement.dataset.theme === 'dark' ? 'light' : 'dark';
    setTheme(next);
}

